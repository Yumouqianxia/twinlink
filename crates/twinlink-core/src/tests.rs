use super::*;
use crate::pairing::{test_server, SERVER_PREFIX};

const TEST_PREFIX: &str = "twinlink-test-prefix";

/// Open two Cores and pipe a chat session through a real loopback socket, without
/// the supervisor or EasyTier. The derived addresses are irrelevant here; only
/// the shared secret must match on both sides.
async fn pair() -> (Arc<Core>, Arc<Core>, tempfile::TempDir, tempfile::TempDir, CancellationToken) {
    let left_dir = tempfile::tempdir().unwrap();
    let right_dir = tempfile::tempdir().unwrap();
    let left =
        Core::open(left_dir.path().join("data"), left_dir.path().into(), PathBuf::new()).unwrap();
    let right =
        Core::open(right_dir.path().join("data"), right_dir.path().into(), PathBuf::new()).unwrap();
    left.import_server_code(&pairing::encode_server_code(&test_server(TEST_PREFIX)).unwrap()).await.unwrap();
    let invitation = left.create_room().await.unwrap();
    right.join_room(&invitation).await.unwrap();
    let room_id = left.snapshot().await.unwrap().room.unwrap().room_id;
    let left_generation = left.inner.lock().await.generation;
    let right_generation = right.inner.lock().await.generation;
    let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
    let addr = listener.local_addr().unwrap();
    let cancel = CancellationToken::new();
    let server = left.clone();
    let server_room = room_id.clone();
    let stop = cancel.clone();
    tokio::spawn(async move {
        let (stream, _) = listener.accept().await.unwrap();
        let _ = server.session(stream, "a-long-test-secret", true, stop, &server_room, left_generation).await;
        server.mark_disconnected().await;
    });
    let client = right.clone();
    let stop = cancel.clone();
    tokio::spawn(async move {
        let stream = TcpStream::connect(addr).await.unwrap();
        let _ = client.session(stream, "a-long-test-secret", false, stop, &room_id, right_generation).await;
        client.mark_disconnected().await;
    });
    timeout(Duration::from_secs(5), async {
        loop {
            if left.snapshot().await.unwrap().connection == "connected"
                && right.snapshot().await.unwrap().connection == "connected"
            {
                break;
            }
            sleep(Duration::from_millis(10)).await;
        }
    })
    .await
    .unwrap();
    (left, right, left_dir, right_dir, cancel)
}

