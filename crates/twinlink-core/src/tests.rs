#[derive(Default)]
struct FakeState {
    events: Vec<mailbox::IncomingEvent>,
    /// file_id -> (sender, chunk_count, chunk_bytes, encrypted_size, chunks)
    files: std::collections::HashMap<String, FakeFile>,
    /// file_id -> chunks actually GET-able; a full upload flips this.
    accepted: std::collections::HashSet<String>,
    requested_chunks: Vec<(String, u64)>,
    posts: usize,
}

struct FakeFile {
    sender: String,
    chunk_count: u64,
    encrypted_size: u64,
    chunks: std::collections::HashMap<u64, Vec<u8>>,
    complete: bool,
}

#[derive(Clone)]
struct FakeServer {
    room_id: String,
    host: Arc<tokio::sync::Mutex<FakeState>>,
    /// Chunk indices whose PUT fails with 507 to simulate quota exhaustion.
    quota_at: Arc<tokio::sync::Mutex<Option<u64>>>,
    /// When set, the first PUT for that chunk index returns a transient 503.
    transient: Arc<tokio::sync::Mutex<Option<u64>>>,
    transient_hits: Arc<tokio::sync::Mutex<Vec<u64>>>,
}

#[async_trait::async_trait]
impl mailbox::Transport for FakeServer {
    async fn request(&self, request: mailbox::HttpRequest) -> Result<mailbox::HttpResponse, mailbox::MailboxError> {
        use mailbox::{HttpResponse, MailboxError};
        let url = request.url.clone();
        let path = url.splitn(4, '/').nth(3).unwrap_or("").to_string();
        let path = format!("/{path}");
        let method = request.method;
        // POST /v1/rooms
        if method == "POST" && path == "/v1/rooms" {
            let body = serde_json::json!({
                "roomId": self.room_id,
                "ttlSeconds": 604800,
                "chunkBytes": mailbox::CHUNK_BYTES,
                "maxFileBytes": mailbox::MAX_FILE_BYTES,
            });
            return Ok(HttpResponse { status: 200, body: serde_json::to_vec(&body).unwrap() });
        }
        // events collection
        if method == "POST" && path.ends_with("/events") {
            let value: serde_json::Value = serde_json::from_slice(&request.body).unwrap();
            let id = value["id"].as_str().unwrap().to_string();
            let mut state = self.host.lock().await;
            state.posts += 1;
            // Idempotent: same id => return the same receipt.
            state.events.push(mailbox::IncomingEvent {
                id: id.clone(),
                sender: value["sender"].as_str().unwrap().to_string(),
                recipient: value["recipient"].as_str().unwrap().to_string(),
                payload: value["payload"].as_str().unwrap().to_string(),
                created_at: 1,
                expires_at: 100,
            });
            let out = serde_json::json!({ "id": id, "createdAt": 1, "expiresAt": 100 });
            return Ok(HttpResponse { status: 200, body: serde_json::to_vec(&out).unwrap() });
        }
        // list events
        if method == "GET" && path.contains("/events?") {
            let recipient = path.split("recipient=").nth(1).unwrap_or("").to_string();
            let state = self.host.lock().await;
            let events: Vec<_> = state.events.iter().filter(|e| e.recipient == recipient).cloned().collect();
            let out = serde_json::json!({ "events": events });
            return Ok(HttpResponse { status: 200, body: serde_json::to_vec(&out).unwrap() });
        }
        // delete event
        if method == "DELETE" && path.contains("/events/") {
            let parts: Vec<&str> = path.split('/').collect();
            let id = parts[5].split('?').next().unwrap().to_string();
            let mut state = self.host.lock().await;
            state.events.retain(|e| e.id != id);
            return Ok(HttpResponse { status: 204, body: Vec::new() });
        }
        // declare file
        if method == "POST" && path.ends_with("/files") {
            let value: serde_json::Value = serde_json::from_slice(&request.body).unwrap();
            let id = value["id"].as_str().unwrap().to_string();
            let encrypted_size = value["encryptedSize"].as_u64().unwrap();
            let chunk_count = value["chunkCount"].as_u64().unwrap();
            let mut state = self.host.lock().await;
            state.files.entry(id.clone()).or_insert(FakeFile {
                sender: value["sender"].as_str().unwrap().to_string(),
                chunk_count,
                encrypted_size,
                chunks: Default::default(),
                complete: false,
            });
            let out = manifest_json(&state, &id);
            return Ok(HttpResponse { status: 200, body: serde_json::to_vec(&out).unwrap() });
        }
        // complete file
        if method == "POST" && path.ends_with("/complete") {
            let parts: Vec<&str> = path.split('/').collect();
            let id = parts[5].to_string();
            let mut state = self.host.lock().await;
            if let Some(file) = state.files.get_mut(&id) {
                if file.chunks.len() as u64 == file.chunk_count {
                    file.complete = true;
                    state.accepted.insert(id.clone());
                }
            }
            let out = manifest_json(&state, &id);
            return Ok(HttpResponse { status: 200, body: serde_json::to_vec(&out).unwrap() });
        }
        // PUT / GET chunk
        if path.contains("/chunks/") {
            let parts: Vec<&str> = path.split('/').collect();
            // /v1/rooms/{room}/files/{id}/chunks/{index}
            let id = parts[5].to_string();
            let index: u64 = parts[7].parse().unwrap();
            if method == "PUT" {
                {
                    let mut transient = self.transient.lock().await;
                    if *transient == Some(index) {
                        *transient = None;
                        self.transient_hits.lock().await.push(index);
                        return Err(MailboxError::api(503, "unavailable"));
                    }
                }
                if let Some(at) = *self.quota_at.lock().await {
                    if index >= at {
                        return Err(MailboxError::api(507, "storage_full"));
                    }
                }
                let mut state = self.host.lock().await;
                if let Some(file) = state.files.get_mut(&id) {
                    file.chunks.insert(index, request.body.clone());
                }
                let sha = crate::crypto::sha256_hex(&request.body);
                let out = serde_json::json!({ "index": index, "sha256": sha });
                return Ok(HttpResponse { status: 200, body: serde_json::to_vec(&out).unwrap() });
            } else {
                let mut state = self.host.lock().await;
                state.requested_chunks.push((id.clone(), index));
                if !state.accepted.contains(&id) {
                    return Err(MailboxError::api(404, "not_found"));
                }
                let bytes = state.files.get(&id).and_then(|f| f.chunks.get(&index).cloned())
                    .ok_or_else(|| MailboxError::api(404, "not_found"))?;
                return Ok(HttpResponse { status: 200, body: bytes });
            }
        }
        // GET manifest
        if method == "GET" && path.contains("/files/") {
            let parts: Vec<&str> = path.split('/').collect();
            let id = parts[5].to_string();
            let state = self.host.lock().await;
            if !state.files.contains_key(&id) {
                return Err(MailboxError::api(404, "not_found"));
            }
            let out = manifest_json(&state, &id);
            return Ok(HttpResponse { status: 200, body: serde_json::to_vec(&out).unwrap() });
        }
        // DELETE file
        if method == "DELETE" && path.contains("/files/") {
            let parts: Vec<&str> = path.split('/').collect();
            let id = parts[5].to_string();
            let mut state = self.host.lock().await;
            state.files.remove(&id);
            state.accepted.remove(&id);
            return Ok(HttpResponse { status: 204, body: Vec::new() });
        }
        Err(MailboxError::api(404, "not_found"))
    }
}

fn manifest_json(state: &FakeState, id: &str) -> serde_json::Value {
    let file = state.files.get(id).unwrap();
    let mut received: Vec<u64> = file.chunks.keys().copied().collect();
    received.sort_unstable();
    serde_json::json!({
        "id": id,
        "sender": file.sender,
        "encryptedSize": file.encrypted_size,
        "chunkCount": file.chunk_count,
        "chunkBytes": mailbox::CHUNK_BYTES,
        "received": received,
        "complete": file.complete,
        "expiresAt": 100,
    })
}

struct MailboxPair {
    left: Arc<Core>,
    right: Arc<Core>,
    left_dir: tempfile::TempDir,
    right_dir: tempfile::TempDir,
    server: FakeServer,
    cancel: CancellationToken,
}

async fn mailbox_pair() -> MailboxPair {
    let server = test_server(TEST_PREFIX);
    let stored = crate::pairing::StoredRoom::create(server.clone(), "host").unwrap();
    let spec = stored.spec().unwrap();
    let mut peer = stored.clone();
    peer.role = "join".into();
    let fake = FakeServer {
        room_id: spec.room_id.clone(),
        host: Arc::new(tokio::sync::Mutex::new(FakeState::default())),
        quota_at: Arc::new(tokio::sync::Mutex::new(None)),
        transient: Arc::new(tokio::sync::Mutex::new(None)),
        transient_hits: Arc::new(tokio::sync::Mutex::new(Vec::new())),
    };
    let left_dir = tempfile::tempdir().unwrap();
    let right_dir = tempfile::tempdir().unwrap();
    let left = Core::open(left_dir.path().join("data"), left_dir.path().into(), PathBuf::new()).unwrap();
    let right = Core::open(right_dir.path().join("data"), right_dir.path().into(), PathBuf::new()).unwrap();
    for core in [&left, &right] {
        *core.transport.lock().unwrap() = Some(Arc::new(fake.clone()));
    }
    left.install_room(stored.clone()).await.unwrap();
    right.install_room(peer.clone()).await.unwrap();
    let cancel = CancellationToken::new();
    let l = left.clone();
    let sc = cancel.clone();
    tokio::spawn(async move { l.mailbox_loop().await; let _ = sc; });
    let r = right.clone();
    let sc = cancel.clone();
    tokio::spawn(async move { r.mailbox_loop().await; let _ = sc; });
    MailboxPair { left, right, left_dir, right_dir, server: fake, cancel }
}

async fn wait_transfer(core: &Arc<Core>, index: usize, status: &str) {
    timeout(Duration::from_secs(20), async {
        loop {
            let snapshot = core.snapshot().await.unwrap();
            if snapshot.transfers.get(index).map(|t| t.status.as_str()) == Some(status) {
                break;
            }
            sleep(Duration::from_millis(20)).await;
        }
    })
    .await
    .unwrap();
}



#[tokio::test]
async fn sender_can_withdraw_a_stored_file_before_consent() {
    let MailboxPair { left, right, left_dir, right_dir: _right_dir, server, cancel } = mailbox_pair().await;
    let path = left_dir.path().join("withdraw.txt");
    tokio::fs::write(&path, b"withdraw this").await.unwrap();
    let transfer = left.offer_file(path).await.unwrap();
    wait_transfer(&right, 0, "offered").await;
    left.cancel_transfer(Uuid::parse_str(&transfer.id).unwrap()).await.unwrap();
    wait_transfer(&right, 0, "cancelled").await;
    timeout(Duration::from_secs(5), async {
        while !server.host.lock().await.files.is_empty() { sleep(Duration::from_millis(20)).await; }
    }).await.unwrap();
    assert_eq!(left.snapshot().await.unwrap().transfers[0].status, "cancelled");
    assert!(server.host.lock().await.requested_chunks.is_empty());
    cancel.cancel();
}

#[tokio::test]
async fn unverifiable_event_is_quarantined_without_ack_or_receipt() {
    use base64::Engine;
    let MailboxPair { right, server, cancel, left_dir: _left_dir, right_dir: _right_dir, .. } = mailbox_pair().await;
    let id = Uuid::new_v4().to_string();
    server.host.lock().await.events.push(mailbox::IncomingEvent {
        id: id.clone(), sender: "host".into(), recipient: "join".into(),
        payload: base64::engine::general_purpose::URL_SAFE_NO_PAD.encode([1u8;41]),
        created_at: 1, expires_at: 100,
    });
    timeout(Duration::from_secs(5), async {
        loop {
            let n: i64 = rusqlite::Connection::open(right.data_dir.join("twinlink.db")).unwrap().query_row("SELECT count(*) FROM quarantined_events", [], |r|r.get(0)).unwrap();
            if n == 1 { break; }
            sleep(Duration::from_millis(20)).await;
        }
    }).await.unwrap();
    assert!(right.snapshot().await.unwrap().messages.is_empty());
    assert!(server.host.lock().await.events.iter().any(|event|event.id==id));
    assert_eq!(server.host.lock().await.posts, 0);
    cancel.cancel();
}
