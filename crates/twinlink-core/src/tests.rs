#[test]
fn server_code_round_trips_and_redacts_secrets() {
    let server = test_server(TEST_PREFIX);
    let code = pairing::encode_server_code(&server).unwrap();
    assert!(code.starts_with(SERVER_PREFIX));
    let parsed = pairing::parse_server_code(&code).unwrap();
    assert_eq!(parsed, server);
    // The token and PEM must never leak through Debug output.
    let debug = format!("{server:?}");
    assert!(!debug.contains(&server.access_token));
    assert!(!debug.contains("BEGIN CERTIFICATE"));
    assert!(debug.contains("<redacted>"));
}

#[test]
fn malformed_codes_are_rejected() {
    let server = test_server(TEST_PREFIX);
    let code = pairing::encode_server_code(&server).unwrap();
    let body = code.strip_prefix(SERVER_PREFIX).unwrap();

    // Wrong prefix.
    assert!(pairing::parse_server_code(&format!("TL1.{body}")).is_err());
    // Oversized input.
    let huge = format!("{SERVER_PREFIX}{}", "A".repeat(64 * 1024));
    assert!(pairing::parse_server_code(&huge).is_err());
    // A tampered body no longer decodes to valid JSON/config.
    let mut tampered = body.to_string();
    tampered.pop();
    assert!(pairing::parse_server_code(&format!("{SERVER_PREFIX}{tampered}")).is_err());
}

#[test]
fn invite_rejects_unknown_fields_and_forces_join_role() {
    use base64::engine::general_purpose::URL_SAFE_NO_PAD;
    use base64::Engine as _;

    let server = test_server(TEST_PREFIX);
    let host = StoredRoom::create(server.clone(), "host").unwrap();
    let invite = host.invite_code().unwrap();
    let joined = StoredRoom::from_invite(&invite).unwrap();
    // Even though the invite was generated by a host, the importer always joins.
    assert_eq!(joined.role, "join");
    assert_eq!(joined.seed, host.seed);

    // Injecting an unknown field such as `customParam` must be rejected before
    // anything is parsed into a room.
    let payload = serde_json::json!({
        "v": 1,
        "seed": host.seed,
        "server": server,
        "customParam": ["--evil"]
    });
    let evil = format!(
        "{}{}",
        pairing::INVITE_PREFIX,
        URL_SAFE_NO_PAD.encode(serde_json::to_vec(&payload).unwrap())
    );
    assert!(StoredRoom::from_invite(&evil).is_err());
}

