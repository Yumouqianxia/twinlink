/* ---------- supervisor behaviour ---------- */

fn fast_policy() -> Policy {
    Policy {
        connect_timeout: Duration::from_millis(300),
        handshake_timeout: Duration::from_millis(300),
        retry_base: Duration::from_millis(20),
        retry_cap: Duration::from_millis(80),
        max_failures: 3,
        jitter: false,
    }
}

#[test]
fn backoff_is_bounded_and_monotonic() {
    let policy = Policy {
        connect_timeout: Duration::from_secs(1),
        handshake_timeout: Duration::from_secs(1),
        retry_base: Duration::from_millis(10),
        retry_cap: Duration::from_millis(100),
        max_failures: 10,
        jitter: false,
    };
    let cap = policy.retry_cap.as_millis() as u64;
    let mut previous = 0;
    for failures in 1..=12u32 {
        let delay = policy.delay(failures).as_millis() as u64;
        assert!(delay >= previous, "delay must not shrink: {delay} < {previous}");
        assert!(delay <= cap, "delay must stay capped: {delay} > {cap}");
        previous = delay;
    }
    assert_eq!(policy.delay(20).as_millis() as u64, cap, "large counts clamp to the cap");
}

#[tokio::test]
async fn manual_pause_stops_supervisor_and_resume_restarts_it() {
    let dir = tempfile::tempdir().unwrap();
    // Point at a nonexistent engine: every attempt fails immediately, but the
    // supervisor must still honour pause long before the failure budget.
    let core = Core::open_with_policy(
        dir.path().join("data"),
        dir.path().into(),
        std::env::current_exe().unwrap(),
        fast_policy(),
    )
    .unwrap();
    core.import_server_code(&pairing::encode_server_code(&test_server(TEST_PREFIX)).unwrap())
        .await
        .unwrap();
    core.create_room().await.unwrap();

    let runner = core.clone();
    let handle = tokio::spawn(async move { runner.run().await });

    // Let it fail at least once, then pause.
    timeout(Duration::from_secs(2), async {
        loop {
            if core.snapshot().await.unwrap().reconnect.is_some() {
                break;
            }
            sleep(Duration::from_millis(10)).await;
        }
    })
    .await
    .unwrap();
    core.pause().await.unwrap();
    assert!(core.snapshot().await.unwrap().paused);
    // Wait past several retry windows; paused state must hold and no child runs.
    sleep(Duration::from_millis(400)).await;
    let paused = core.snapshot().await.unwrap();
    assert!(paused.paused);
    assert_eq!(paused.connection, "disconnected");

    core.resume().await.unwrap();
    assert!(!core.snapshot().await.unwrap().paused);

    core.shutdown().await;
    handle.abort();
}

