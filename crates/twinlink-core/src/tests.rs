#[tokio::test]
async fn mailbox_file_requires_consent_and_preserves_existing() {
    let MailboxPair { left, right, left_dir, right_dir, server, cancel } = mailbox_pair().await;
    let bytes: Vec<u8> = (0..1024 * 1024 + 31).map(|i| (i % 251) as u8).collect();
    let source = left_dir.path().join("报告.bin");
    tokio::fs::write(&source, &bytes).await.unwrap();
    tokio::fs::write(right_dir.path().join("报告.bin"), b"existing").await.unwrap();
    let sent = left.offer_file(source).await.unwrap();
    let id = Uuid::parse_str(&sent.id).unwrap();
    // The offer reaches the recipient as a pending consent prompt, and no
    // download request is ever issued before the recipient accepts.
    timeout(Duration::from_secs(10), async {
        while right.snapshot().await.unwrap().transfers.is_empty() {
            sleep(Duration::from_millis(20)).await;
        }
    })
    .await
    .unwrap();
    assert_eq!(right.snapshot().await.unwrap().transfers[0].status, "offered");
    sleep(Duration::from_millis(400)).await;
    assert!(right.snapshot().await.unwrap().transfers[0].status == "offered");
    assert!(server.host.lock().await.requested_chunks.is_empty());
    assert!(!right_dir.path().join("报告 (1).bin").exists());

    right.accept_file(id).await.unwrap();
    wait_transfer(&right, 0, "completed").await;
    wait_transfer(&left, 0, "completed").await;
    assert_eq!(tokio::fs::read(right_dir.path().join("报告.bin")).await.unwrap(), b"existing");
    assert_eq!(tokio::fs::read(right_dir.path().join("报告 (1).bin")).await.unwrap(), bytes);
    cancel.cancel();
}

