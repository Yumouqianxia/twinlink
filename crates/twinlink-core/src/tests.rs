#[tokio::test]
async fn mailbox_upload_survives_transient_error_and_reuses_spool() {
    let MailboxPair { left, right, left_dir, right_dir, server, cancel } = mailbox_pair().await;
    let bytes: Vec<u8> = (0..2 * 1024 * 1024 + 7).map(|i| (i % 199) as u8).collect();
    let source = left_dir.path().join("resume.bin");
    tokio::fs::write(&source, &bytes).await.unwrap();
    // Force the second chunk to fail once with a retryable 503.
    *server.transient.lock().await = Some(1);
    left.offer_file(source).await.unwrap();
    // The upload retries the failed chunk from the persisted encrypted spool
    // (never regenerating bytes) and eventually delivers the intact file.
    timeout(Duration::from_secs(20), async {
        loop {
            if right.snapshot().await.unwrap().transfers.iter().any(|t| t.status == "offered") {
                break;
            }
            sleep(Duration::from_millis(20)).await;
        }
    })
    .await
    .unwrap();
    assert_eq!(*server.transient_hits.lock().await, vec![1]);
    right.accept_file(Uuid::parse_str(&right.snapshot().await.unwrap().transfers[0].id).unwrap()).await.unwrap();
    wait_transfer(&right, 0, "completed").await;
    assert_eq!(tokio::fs::read(right_dir.path().join("resume.bin")).await.unwrap(), bytes);
    cancel.cancel();
}

